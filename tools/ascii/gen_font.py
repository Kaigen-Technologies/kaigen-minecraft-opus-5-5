# generates src/webcraft/wc_font.h: the 95 printable ascii glyphs of Monocraft as 6x9 cell bitmaps
# usage: python -I tools/ascii/gen_font.py
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "tools", "ascii", "monocraft", "characters.json")
DST = os.path.join(ROOT, "src", "webcraft", "wc_font.h")

CELL_W, CELL_H = 6, 9


def cell_rows(ch):
    # glyph rows start at cell row 1 (row 0 is the ascender gap); descenders reach row 8
    rows = [0] * CELL_H
    for r, line in enumerate(ch["pixels"]):
        bits = 0
        for c, v in enumerate(line):
            if v:
                bits |= 1 << c
        rows[1 + r] = bits
    return rows


def load():
    data = json.load(open(SRC, encoding="utf-8"))
    by = {c["codepoint"]: c for c in data if "codepoint" in c}
    out = []
    for cp in range(32, 127):
        c = by[cp]
        assert len(c["pixels"]) - c.get("descent", 0) == 7, chr(cp)
        assert all(len(r) == 5 for r in c["pixels"]), chr(cp)
        out.append(cell_rows(c))
    return out


def main():
    glyphs = load()
    lines = [
        "// generated by tools/ascii/gen_font.py from Monocraft (c) 2022 Idrees Hassan, SIL OFL 1.1 (MONOCRAFT_OFL.txt)",
        "#ifndef WC_FONT_H",
        "#define WC_FONT_H",
        "",
        "#define WC_FONT_W %d" % CELL_W,
        "#define WC_FONT_H_PX %d" % CELL_H,
        "#define WC_FONT_GLYPHS 95",
        "",
        "// glyph g is ascii 32 + g; row r of the cell, bit c = column c (column 5 is always empty)",
        "static const u8 wc_font_rows[WC_FONT_GLYPHS * WC_FONT_H_PX] = {",
    ]
    for i, rows in enumerate(glyphs):
        ch = chr(32 + i)
        name = {"\\": "backslash"}.get(ch, ch)
        lines.append("    " + ", ".join("0x%02x" % b for b in rows) + ", // " + name)
    lines += ["};", "", "#endif", ""]
    with open(DST, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", DST, len(glyphs), "glyphs")


if __name__ == "__main__":
    sys.exit(main())
